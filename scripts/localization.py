#!/usr/bin/env python3
"""Compile explicit English/Vietnamese UI catalog and audit source-string coverage.
This is not an automatic translator. A new source literal requires translation or an explicit exclusion.
"""
import argparse, collections, hashlib, json, pathlib, re, sys
ROOT=pathlib.Path(__file__).resolve().parents[1]
TOKEN=re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|\'(?:[^\'\\]|\\.)*\'|(@"(?:[^"\\]|\\.)*"(?:\s*@?"(?:[^"\\]|\\.)*")*)|"(?:[^"\\]|\\.)*"')
def decode(raw):
    # Match Objective-C escapes without corrupting Unicode.
    return re.sub(r'\\([nrt"\\])',lambda m:{'n':'\n','r':'\r','t':'\t','"':'"','\\':'\\'}[m[1]],raw)
def literals(source):
    for match in TOKEN.finditer(source):
        if match[1]:
            yield match,decode(''.join(re.findall(r'@?"((?:[^"\\]|\\.)*)"',match[1])))
def objc(value):return '@'+json.dumps(value,ensure_ascii=False)
def sources():
    return sorted(p for p in (ROOT/'tweak/Sources').rglob('*') if p.suffix in ('.m','.x','.h') and p.name not in ('SGLocalization.m','SGFlagList.m'))
def signature(s):
    return sorted(re.findall(r'%(?!%)(?:\d+\$)?[-+ #0]*(?:\d+|\*)?(?:\.(?:\d+|\*))?(?:hh|ll|[hljztL])?[@diuoxXfFeEgGaAcsp]',re.sub(r'(?<=\d)%(?=[ ,.]|$)', '', s.replace('%%',''))))
def compile_catalog():
    catalog=json.loads((ROOT/'localization/catalog.json').read_text())
    errors=[]
    for key,value in catalog.items():
        if not value.strip():errors.append(f'Empty Vietnamese: {key!r}')
        if signature(key)!=signature(value):errors.append(f'Format arguments differ: {key!r}')
        if sorted(re.findall(r'\{[a-z]+\}',key))!=sorted(re.findall(r'\{[a-z]+\}',value)):errors.append(f'Placeholders differ: {key!r}')
    if errors:raise ValueError('\n'.join(errors))
    generated='// Generated by scripts/localization.py; edit localization/catalog.json.\n'+''.join(f'{objc(k)}: {objc(v)},\n' for k,v in sorted(catalog.items()))
    return catalog,generated

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--generate',action='store_true');parser.add_argument('--snapshot-exclusions',action='store_true');args=parser.parse_args()
    catalog,generated=compile_catalog();target=ROOT/'tweak/Sources/Core/SGUICatalog.inc'
    if args.generate:target.write_text(generated)
    elif not target.exists() or target.read_text()!=generated:raise ValueError('Generated UI catalog is stale')
    # Per-file fingerprints include all non-UI literals. This makes new prose in an old file fail too.
    excluded=collections.defaultdict(dict)
    for p in sources():
        for _,key in literals(p.read_text()):
            if key not in catalog and re.search('[A-Za-z]',key):
                excluded[str(p.relative_to(ROOT))][key]='technical identifier, external data, protocol token, diagnostic, proper name, legal original or unchanged AI instruction'
    baseline=ROOT/'localization/non-ui-literals.json'
    if args.snapshot_exclusions:baseline.write_text(json.dumps(excluded,ensure_ascii=False,indent=2,sort_keys=True)+'\n')
    allowed=json.loads(baseline.read_text()) if baseline.exists() else {}
    missing=[]
    for path,keys in excluded.items():
        for key in keys:
            if key not in allowed.get(path,{}):missing.append(f'{path}: {key!r}')
    if missing:raise ValueError('Unclassified source strings (translate UI; document technical data):\n'+'\n'.join(missing))
    print(f'PASS: {len(catalog)} English/Vietnamese keys; format arguments, placeholders, generated catalog and source-string inventory')
if __name__=='__main__':
    try:main()
    except (ValueError,json.JSONDecodeError) as e:print(e,file=sys.stderr);sys.exit(1)

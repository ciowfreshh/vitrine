BOOL SGSYNAVietnamese(void) {
    id value = [NSUserDefaults.standardUserDefaults objectForKey:SGKeySYNALanguage];
    return value ? [value integerValue] == 0 : YES;
}
void SGSetSYNALanguage(BOOL vietnamese) {
    [NSUserDefaults.standardUserDefaults setInteger:vietnamese ? 0 : 1 forKey:SGKeySYNALanguage];
}

NSString *SGVI(NSString *text) {
    if (!text.length) return text;
    return catalog()[text] ?: text;
}

NSString *SGVIError(NSString *text) {
    NSString *localized = SGVI(text);
    if (!text.length || ![localized isEqualToString:text]) return localized;
    // Regex groups match format arguments after upstream validation and error classification.
    static NSArray<NSArray *> *rules;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        NSMutableArray *parsed = [NSMutableArray array];
        NSRegularExpression *placeholder = [NSRegularExpression regularExpressionWithPattern:@"%(@|ld|lu)" options:0 error:nil];
        for (NSString *format in catalog()) {
            NSString *translation = catalog()[format];
            if (format.length < 15) continue;
            NSArray<NSTextCheckingResult *> *fields = [placeholder matchesInString:format options:0 range:NSMakeRange(0, format.length)];
            if (!fields.count || [placeholder numberOfMatchesInString:translation options:0 range:NSMakeRange(0, translation.length)] != fields.count) continue;
            NSMutableString *pattern = [NSMutableString stringWithString:@"^"];
            NSUInteger offset = 0;
            for (NSTextCheckingResult *field in fields) {
                [pattern appendString:[NSRegularExpression escapedPatternForString:[format substringWithRange:NSMakeRange(offset, field.range.location - offset)]]];
                [pattern appendString:[format characterAtIndex:field.range.location + 1] == '@' ? @"(.+?)" : @"([0-9]+)"];
                offset = NSMaxRange(field.range);
            }
            [pattern appendString:[NSRegularExpression escapedPatternForString:[format substringFromIndex:offset]]];
            [pattern appendString:@"$"];
            NSRegularExpression *expression = [NSRegularExpression regularExpressionWithPattern:pattern options:0 error:nil];
            if (expression) [parsed addObject:@[expression, translation]];
        }
        rules = parsed;
    });
    for (NSArray *rule in rules) {
        NSTextCheckingResult *match = [rule[0] firstMatchInString:text options:0 range:NSMakeRange(0, text.length)];
        if (!match) continue;
        NSMutableString *answer = [rule[1] mutableCopy];
        NSRegularExpression *placeholder = [NSRegularExpression regularExpressionWithPattern:@"%(@|ld|lu)" options:0 error:nil];
        NSArray<NSTextCheckingResult *> *fields = [placeholder matchesInString:answer options:0 range:NSMakeRange(0, answer.length)];
        for (NSUInteger i = fields.count; i > 0; i--)
            [answer replaceCharactersInRange:fields[i - 1].range withString:[text substringWithRange:[match rangeAtIndex:i]]];
        return answer;
    }
    return text;
}
